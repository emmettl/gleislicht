 await clock.fill('44200'); await expect(status).toHaveAttribute('data-terrain-status', 'tunnel'); await expect(scene).toHaveCount(0)
 await clock.fill('44510'); await page.getByRole('button', { name: /Resume motion/ }).click()
 await expect(card).toHaveAttribute('data-phase', 'complete'); await expect(card).toContainText('Arrived · Rochers-de-Naye')
 await card.getByRole('button', { name: /Replay journey/ }).click(); await expect(clock).toHaveValue('41640')
 await card.getByRole('button', { name: 'Journey details', exact: true }).click()
 await card.getByRole('combobox', { name: 'Direction', exact: true }).selectOption('descent')
 await expect(clock).toHaveValue('44820'); await expect(scene).toHaveAttribute('data-rendered', 'true')
 await card.getByRole('button', { name: 'Journey details', exact: true }).click()
 await clock.fill('44860'); await expect(status).toHaveAttribute('data-terrain-status', 'tunnel'); await expect(scene).toHaveCount(0)
 await clock.fill('45450'); await expect(status).toHaveAttribute('data-terrain-status', 'covered')
 await clock.fill('46000'); await expect(scene).toHaveAttribute('data-rendered', 'true')
 await page.screenshot({ path: info.outputPath('rochers-descent-terrain.png') })
 await card.getByRole('button', { name: 'Return to map', exact: true }).click(); await expect(scene).toHaveCount(0); await expect(clock).toHaveValue('46000')

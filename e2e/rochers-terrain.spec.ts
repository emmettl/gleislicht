 await card.getByRole('button', { name: 'Journey details', exact: true }).click()
 await card.locator('nav button').filter({ has: page.getByText('Caux', { exact: true }) }).click()
 await expect(clock).toHaveValue('42960'); await expect(scene).toHaveAttribute('data-rendered', 'true'); await expect(scene).toHaveAttribute('data-stopped', 'true')
 await page.screenshot({ path: info.outputPath('rochers-caux-terrain.png') })
 await clock.fill('43620'); await page.getByRole('button', { name: /Resume motion/ }).click()
 await expect(status).toHaveAttribute('data-terrain-status', 'covered'); await expect(scene).toHaveCount(0)
 await expect(page.getByRole('button', { name: /Pause motion/ })).toBeVisible(); await page.getByRole('button', { name: /Pause motion/ }).click()
 await clock.fill('43700'); await expect(scene).toHaveAttribute('data-rendered', 'true')

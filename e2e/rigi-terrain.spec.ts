test('an unavailable Arth-Goldau approach can switch to Vitznau without showing the wrong terrain', async ({ page, isMobile }) => {
  await page.route('**/arth-goldau-rigi-corridor.json', r => r.fulfill({ status: 503, body: 'Unavailable' }))
  await openRigi(page, isMobile)
  await page.getByRole('button', { name: /Climb Arth-Goldau/ }).click()
  await expect(page.locator('.journey-card')).toContainText('Rigi terrain unavailable')
  await expect(page.locator('.journey-card')).toContainText('Arth-Goldau → Rigi Kulm')
  await expect(page.locator('.journey-card')).not.toContainText('Vitznau')
  await expect(page.locator('.scene canvas')).toHaveCount(0)
  await page.getByRole('button', { name: /Climb Vitznau/ }).click()
  await expect(page.locator('.rigi-terrain-profile')).toContainText('Rise from Vitznau')
})

